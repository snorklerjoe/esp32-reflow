"""PlatformIO pre-build script: gzip web/ assets into src/generated/web_assets.h.

The header is only rewritten when its content changes, so unchanged assets
don't trigger a recompile.
"""
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO/SCons)

ASSETS = [
    # (file in web/, C identifier, content type)
    ("index.html", "INDEX_HTML", "text/html; charset=utf-8"),
    ("app.css", "APP_CSS", "text/css; charset=utf-8"),
    ("app.js", "APP_JS", "application/javascript; charset=utf-8"),
]

project_dir = env.subst("$PROJECT_DIR")  # noqa: F821
web_dir = os.path.join(project_dir, "web")
out_path = os.path.join(project_dir, "src", "generated", "web_assets.h")

parts = [
    "// AUTO-GENERATED by scripts/embed_web.py from web/ - do not edit.\n",
    "#pragma once\n#include <Arduino.h>\n\n",
]
for filename, ident, ctype in ASSETS:
    with open(os.path.join(web_dir, filename), "rb") as f:
        raw = f.read()
    data = gzip.compress(raw, compresslevel=9, mtime=0)
    rows = []
    for i in range(0, len(data), 20):
        rows.append("  " + ",".join("0x%02x" % b for b in data[i:i + 20]))
    parts.append("// %s: %d bytes raw, %d gzipped\n" % (filename, len(raw), len(data)))
    parts.append('static const char %s_TYPE[] = "%s";\n' % (ident, ctype))
    parts.append("static const size_t %s_LEN = %d;\n" % (ident, len(data)))
    parts.append("static const uint8_t %s_GZ[] PROGMEM = {\n%s\n};\n\n" % (ident, ",\n".join(rows)))

content = "".join(parts)
os.makedirs(os.path.dirname(out_path), exist_ok=True)
old = None
if os.path.isfile(out_path):
    with open(out_path, encoding="utf-8") as f:
        old = f.read()
if old != content:
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(content)
    print("embed_web: regenerated %s" % os.path.relpath(out_path, project_dir))
